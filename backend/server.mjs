function newEnvelopeId() {
  const rand = crypto.randomBytes(8).toString("hex").toUpperCase();
  return `${ENVELOPE_PREFIX}-${Date.now().toString(36).toUpperCase()}-${rand}`;
}

function newInvitationToken() {
  return crypto.randomBytes(32).toString("base64url");
}

function tokenHash(token) {
  return crypto.createHash("sha256").update(token).digest("hex");
}

function requireDatabase() {
  if (!pool) throw new Error("Database is not configured");
}

function sha256Hex(bytes) {
  return crypto.createHash("sha256").update(bytes).digest("hex");
}

function base64ToUint8(base64) {
  return Uint8Array.from(Buffer.from(base64, "base64"));
}

function limitedText(value, maxLength = 300) {
  return typeof value === "string" ? value.trim().slice(0, maxLength) : "";
}

function buildCompletedProviderData(original, submitted, completedAt) {
  const originalServices = new Map((original.services || []).map((service) => [service.id, service]));
  const services = (submitted.services || []).slice(0, 250).map((service, index) => {
    const originalService = originalServices.get(service?.id);
    return {
      id: originalService?.id || `provider-service-${index + 1}`,
      component: limitedText(service?.component, 300),
      price: limitedText(service?.price, 100),
      source: originalService ? "occu-med" : "provider",
    };
  }).filter((service) => service.component);

  return {
    ...original,
    providerName: limitedText(submitted.providerName) || original.providerName,
    providerContactName: limitedText(submitted.providerContactName),
    providerEmail: limitedText(submitted.providerEmail),
    providerPhone: limitedText(submitted.providerPhone),
    address: {
      street1: limitedText(submitted.address?.street1),
      street2: limitedText(submitted.address?.street2),
      city: limitedText(submitted.address?.city),
      state: limitedText(submitted.address?.state),
      zip: limitedText(submitted.address?.zip, 40),
    },
    services,
    providerSignerName: limitedText(submitted.providerSignerName),
    providerSignerTitle: limitedText(submitted.providerSignerTitle),
    providerSignedDate: completedAt.slice(0, 10),
    agreedElectronic: true,
  };
}

function getClientIp(req) {
  const fwd = req.headers["x-forwarded-for"];
  if (typeof fwd === "string" && fwd.length > 0) return fwd.split(",")[0].trim();
  return req.socket.remoteAddress || "unknown";
}

function allowRequest(req, bucket, limit, windowMs = 60 * 60 * 1000) {
  const now = Date.now();
  if (rateWindows.size > 10_000) {
    for (const [storedKey, value] of rateWindows) {
      if (value.resetAt <= now) rateWindows.delete(storedKey);
    }
  }
  const key = `${bucket}:${getClientIp(req)}`;
  const current = rateWindows.get(key);
  if (!current || current.resetAt <= now) {
    rateWindows.set(key, { count: 1, resetAt: now + windowMs });
    return true;
  }
  if (current.count >= limit) return false;
  current.count += 1;
  return true;
}

function sendJson(res, status, body) {
  res.writeHead(status, {
    "Content-Type": "application/json",
    "Access-Control-Allow-Origin": FRONTEND_ORIGIN,
    "Access-Control-Allow-Headers": "Content-Type, X-Admin-Key",
    "Access-Control-Allow-Methods": "GET,POST,OPTIONS",
  });
  res.end(JSON.stringify(body));
}

function sendPdf(res, bytes, filename) {
  res.writeHead(200, {
    "Content-Type": "application/pdf",
    "Content-Disposition": `attachment; filename="${filename.replace(/[^a-z0-9_.-]/gi, "-")}"`,
    "Content-Length": bytes.length,
    "Access-Control-Allow-Origin": FRONTEND_ORIGIN,
    "Access-Control-Allow-Headers": "Content-Type, X-Admin-Key",
  });
  res.end(bytes);
}

function hasAdminAccess(req) {
  const supplied = typeof req.headers["x-admin-key"] === "string" ? req.headers["x-admin-key"] : "";
  if (!ADMIN_ACCESS_KEY || !supplied) return false;
  const expectedBytes = Buffer.from(ADMIN_ACCESS_KEY);
  const suppliedBytes = Buffer.from(supplied);
  return expectedBytes.length === suppliedBytes.length && crypto.timingSafeEqual(expectedBytes, suppliedBytes);
}

function requireAdminAccess(req, res) {
  if (!ADMIN_ACCESS_KEY) {
    sendJson(res, 503, { error: "Admin access is not configured on the backend." });
    return false;
  }
  if (!hasAdminAccess(req)) {
    sendJson(res, 401, { error: "The admin access code is incorrect." });
    return false;
  }
  return true;
}

function adminInvitationRow(row, includeData = false) {
  const data = row.completed_payload || row.payload || {};
  const result = {
    id: String(row.id),
    documentType: row.document_type,
    status: row.status,
    providerName: data.providerName || "Unnamed provider",
    documentNumber: data.documentNumber || `Invitation ${row.id}`,
    recipientEmail: row.recipient_email || data.providerEmail || "",
    createdAt: row.created_at,
    expiresAt: row.expires_at,
    viewedAt: row.viewed_at || undefined,
    completedAt: row.completed_at || undefined,
    hasCompletedDocument: Boolean(row.pdf_bytes),
  };
  if (includeData) {
    result.data = data;
    result.pdfHash = row.pdf_hash || undefined;
  }
  return result;
}

function readJson(req) {
  return new Promise((resolve, reject) => {
    let raw = "";
    req.on("data", (chunk) => {
      raw += chunk;
      if (raw.length > 12_000_000) {
        reject(new Error("Payload too large"));
        req.destroy();
      }
    });
    req.on("end", () => {
      try {
        resolve(raw ? JSON.parse(raw) : {});
      } catch (e) {
        reject(e);
      }
    });
    req.on("error", reject);
  });
}


async function maybeSendEmail({ to, envelopeId, pdfHash, pdfBytes, certBytes }) {
  const apiKey = process.env.RESEND_API_KEY;
  const from = process.env.MAIL_FROM;
  if (!to || !apiKey || !from) return;

  await fetch("https://api.resend.com/emails", {
    method: "POST",
    headers: {
      Authorization: `Bearer ${apiKey}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      from,
      to,
      subject: `Signed Clinic Memo ${envelopeId}`,
      text: `Envelope ${envelopeId} has been finalized.\nSHA-256: ${pdfHash}`,
      attachments: [
        { filename: `${envelopeId}-signed.pdf`, content: Buffer.from(pdfBytes).toString("base64") },
        { filename: `${envelopeId}-certificate.pdf`, content: Buffer.from(certBytes).toString("base64") },
      ],
    }),
  });
}

