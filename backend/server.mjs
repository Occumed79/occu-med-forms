function verifyInvitationEvidence(row) {
  const originalDocumentHashValid = row.original_document_hash
    ? hashJson(row.payload) === row.original_document_hash
    : null;
  const finalPdfHashValid = row.pdf_hash && row.pdf_bytes
    ? sha256Hex(row.pdf_bytes) === row.pdf_hash
    : null;
  let evidenceHashValid = null;
  if (row.evidence_hash && row.evidence_payload && row.completed_payload && row.signature_hash && row.completed_ip) {
    const completedPayloadHashValid = hashJson(row.completed_payload) === row.evidence_payload.completedPayloadHash;
    const signatureDataHash = sha256Hex(row.completed_payload.providerSignatureData || row.completed_payload.providerSignerName);
    const expectedSignatureHash = hashJson({
      signatureType: row.completed_payload.providerSignatureType,
      signatureDataHash,
      fullName: row.completed_payload.providerSignerName,
      ipAddress: row.completed_ip,
      originalDocumentHash: row.original_document_hash,
    });
    const signatureHashValid = expectedSignatureHash === row.signature_hash
      && row.evidence_payload.signatureHash === row.signature_hash;
    evidenceHashValid = hashJson(row.evidence_payload) === row.evidence_hash
      && completedPayloadHashValid
      && signatureHashValid;
  }
  return {
    valid: originalDocumentHashValid === true && finalPdfHashValid === true && evidenceHashValid === true,
    originalDocumentHashValid,
    finalPdfHashValid,
    evidenceHashValid,
  };
}

function verifyEventChain(invitationId, eventRows) {
  let previousEventHash = null;
  let valid = eventRows.length > 0;
  const events = eventRows.map((event) => {
    const createdAt = new Date(event.created_at).toISOString();
    const expectedHash = hashJson({
      invitationId: String(invitationId),
      eventType: event.event_type,
      details: event.details,
      ipAddress: event.ip_address,
      userAgent: event.user_agent,
      createdAt,
      previousHash: previousEventHash,
    });
    if (event.previous_hash !== previousEventHash || event.event_hash !== expectedHash) valid = false;
    previousEventHash = event.event_hash;
    return {
      eventType: event.event_type,
      details: event.details,
      ipAddress: event.ip_address,
      userAgent: event.user_agent,
      previousHash: event.previous_hash || undefined,
      eventHash: event.event_hash,
      createdAt,
    };
  });
  return { valid, events };
}

