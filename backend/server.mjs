async function maybeSendCompletedProviderDocument({ data, recipientEmail, pdfBytes, certificateBytes }) {
  const apiKey = process.env.RESEND_API_KEY;
  const from = process.env.MAIL_FROM;
  if (!apiKey || !from) return false;
  const recipients = [...new Set([PROVIDER_RESPONSES_TO, recipientEmail || data.providerEmail].filter(Boolean))];
  if (!recipients.length) return false;

  const label = data.documentType === "fee-proposal" ? "Provider Fee Proposal" : "Provider Service Agreement";
  const response = await fetch("https://api.resend.com/emails", {
    method: "POST",
    headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json" },
    body: JSON.stringify({
      from,
      to: recipients,
      subject: `Completed Occu-Med ${label} - ${data.providerName}`,
      text: `${data.providerName} completed document ${data.documentNumber}. The completed document and audit certificate are attached.`,
      attachments: [
        { filename: `${data.documentNumber}-completed.pdf`, content: Buffer.from(pdfBytes).toString("base64") },
        { filename: `${data.documentNumber}-certificate.pdf`, content: Buffer.from(certificateBytes).toString("base64") },
      ],
    }),
  });
  if (!response.ok) throw new Error(`Completed-document email failed (${response.status}): ${await response.text()}`);
  return true;
}

