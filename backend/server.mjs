function sanitizeDatabaseUrl(raw) {
  if (!raw) return "";
  let url = raw.trim();
  if (!url) return "";
  url = url.replace(/[?&]channel_binding=[^&]*/gi, "");
  url = url.replace(/\?$/, "").replace(/&$/, "");
  if (process.env.NODE_ENV === "production" && !/sslmode=/i.test(url)) {
    const sep = url.includes("?") ? "&" : "?";
    url = `${url}${sep}sslmode=require`;
  }
  return url;
}

async function initDbPool() {
  const connStr = sanitizeDatabaseUrl(process.env.DATABASE_URL || "");
  if (!connStr) {
    console.warn("DATABASE_URL not set; database operations will fail at runtime");
    return;
  }
  pool = new Pool({
    connectionString: connStr,
    ssl: process.env.NODE_ENV === "production" ? { rejectUnauthorized: false } : false,
  });
  try {
    const client = await pool.connect();
    try {
      await client.query("select 1");
    } finally {
      client.release();
    }
    console.log("neon database connection ok");
  } catch (err) {
    console.error("neon database connection failed:", err.message);
    await pool.end().catch(() => undefined);
    pool = null;
    throw err;
  }
}

