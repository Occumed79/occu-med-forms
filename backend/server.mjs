async function createAdminSession(req, userId) {
  const token = crypto.randomBytes(48).toString("base64url");
  const expiresAt = new Date(Date.now() + ADMIN_SESSION_HOURS * 60 * 60 * 1000);
  await pool.query(
    `insert into admin_sessions (token_hash, user_id, expires_at, ip_address, user_agent)
     values ($1,$2,$3,$4,$5)`,
    [tokenHash(token), userId, expiresAt.toISOString(), getClientIp(req), req.headers["user-agent"] || "unknown"],
  );
  return { token, expiresAt: expiresAt.toISOString() };
}

function bearerToken(req) {
  const authorization = typeof req.headers.authorization === "string" ? req.headers.authorization : "";
  return authorization.startsWith("Bearer ") ? authorization.slice(7).trim() : "";
}

async function adminSession(req) {
  const token = bearerToken(req);
  if (!token || !pool) return null;
  const { rows } = await pool.query(
    `select s.id, s.user_id, s.expires_at, s.last_activity_at,
            u.email, u.display_name, u.role, u.is_active, u.last_login_at, u.created_at
       from admin_sessions s
       join admin_users u on u.id = s.user_id
      where s.token_hash = $1 and s.revoked_at is null and s.expires_at > now()
        and u.is_active = true limit 1`,
    [tokenHash(token)],
  );
  if (!rows.length) return null;
  const idleMs = Date.now() - new Date(rows[0].last_activity_at).getTime();
  if (idleMs > ADMIN_IDLE_MINUTES * 60 * 1000) {
    await pool.query("update admin_sessions set revoked_at = now() where id = $1", [rows[0].id]);
    return null;
  }
  await pool.query("update admin_sessions set last_activity_at = now() where id = $1", [rows[0].id]);
  return rows[0];
}

async function requireAdminAccess(req, res, permission = "view_documents") {
  const session = await adminSession(req);
  if (!session) {
    sendJson(res, 401, { error: "Your admin session is invalid or has expired." });
    return false;
  }
  if (permission && !hasPermission(session.role, permission)) {
    sendJson(res, 403, { error: "Your account does not have permission for this action." });
    return false;
  }
  return session;
}

